    # ----- helpers -----------------------------------------------------------------------------

    def show(self, name_or_id: str) -> dict:
        result = self.tx(["show", name_or_id])
        self.assertEqual(result.code, 0, result.err)
        return json.loads(result.out)

    def spawn(
        self, name: str, *arguments: str, env: dict | None = None, cwd: str | None = None, fake: str | None = None
    ) -> tuple[dict, dict]:
        """`tx spawn name --tag t --cwd <repo> *arguments` → (record, dump of the fake that ran —
        the record's engine unless `fake` names the binary the command actually invokes)."""
        result = self.tx(
            ["spawn", name, "--tag", "t", "--cwd", cwd or self.repo, *arguments], env=env
        )
        self.assertEqual(result.code, 0, result.err)
        record = self.show(name)
        return record, self.fakes.wait_dump(fake or record["engine"], record["id"])

    def source(
        self,
        name: str,
        cmd: str,
        *,
        engine: str = "claude",
        chat: str | None = None,
        env: dict | None = None,
        cwd: str | None = None,
        chat_cwd: str | None = None,
        transcript: str | None = None,
        state: str = "exited",
    ) -> tuple[str, str]:
        """A crafted source record S with one captured chat; returns (record id, chat id)."""
        session_id = str(uuid.uuid4())
        chat_id = chat or f"c-{uuid.uuid4().hex[:8]}"
        record_cwd = cwd or self.repo
        self.records.llm(
            id=session_id,
            name=name,
            state=state,
            cwd=record_cwd,
            cmd=cmd,
            env=env or {},
            engine=engine,
            created_at=time.time() - 100,
            ended_at=time.time() - 50 if state in ("exited", "archived") else None,
            chats=[
                self.records.chat_ref(
                    session_id=session_id,
                    id=chat_id,
                    cwd=chat_cwd or record_cwd,
                    started_at=time.time() - 100,
                    engine=engine,
                )
            ],
        )
        if transcript is not None:
            self.write_claude_transcript(chat_cwd or record_cwd, chat_id, transcript)
        return session_id, chat_id

    def write_claude_transcript(self, cwd: str, chat_id: str, text: str) -> Path:
        path = self.home.claude_transcript_path(cwd, chat_id)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return path

    def write_rollout(self, chat_id: str, date_dir: str = "2026/09/16", text: str = '{"type":"session_meta"}\n') -> Path:
        path = self.home.codex_home / "sessions" / date_dir / f"rollout-2026-09-16T10-00-00-{chat_id}.jsonl"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        return path

    def fork(self, source_name: str, new_name: str, *arguments: str) -> tuple[dict, dict]:
        result = self.tx(["fork", source_name, new_name, *arguments])
        self.assertEqual(result.code, 0, result.err)
        record = self.show(new_name)
        return record, self.fakes.wait_dump(record["engine"], record["id"])

    def resume(self, source_name: str, *arguments: str, env: dict | None = None):
        result = self.tx(["resume", source_name, *arguments], env=env)
        self.assertEqual(result.code, 0, result.err)
        new_id = re.search(r"cwd=(.*)\)$", result.out).group(0)  # noqa: F841 — presence check only
        return result

    def latest_record_named(self, name: str) -> dict:
        """The most recently created record with this display name (`tx show` prefers the live one,
        which is the same thing right after a spawn)."""
        return self.show(name)

    def worktree_for(self, name: str) -> Path:
        """`$TX_IDE_HOME/worktrees/<repo>-<hash>/<repo>--<name>` for the git fixture."""
        common = Path(self.git.git("rev-parse", "--git-common-dir").strip())
        if not common.is_absolute():
            common = self.git.path / common
        digest = hashlib.sha256(str(common.resolve()).encode()).hexdigest()[:8]
        return self.home.worktrees_dir / f"{self.git.path.name}-{digest}" / f"{self.git.path.name}--{name}"

    def reap_watchers(self) -> None:
        """Kill the detached `_chat-op-watch` children a distiller-path handover leaves behind."""
        if not self.home.chat_ops_dir.is_dir():
            return
        for op_dir in self.home.chat_ops_dir.iterdir():
            subprocess.run(["pkill", "-f", f"_chat-op-watch {op_dir.name}"])

    def handover_seed(self, source_id: str, chat_id: str, task: str, slug: str, op_id: str) -> str:
        home = self.home.path
        return (
            f"You are a tx-ide handover distiller (a temporary helper). Read the predecessor chat "
            f"bundle at {home}/history/{source_id}/{chat_id}/transcript.jsonl . "
            f"Distill a focused, self-contained brief for this task and write it to "
            f"{home}/history/{source_id}/handover-{slug}.md : "
            f"«{task}». Capture only what the new worker needs to start — relevant context, current "
            f"state, constraints, and key file paths — not the whole history. When the brief file is "
            f"saved, run exactly this command and nothing else: "
            f"env TX_IDE_HOME={shlex.quote(str(home))} {shlex.quote(TX_BIN)} _chat-op-finish {shlex.quote(op_id)}"
        )

    def self_catch_up_seed(self, source_id: str, chat_id: str) -> str:
        return (
            f"You are taking over work via tx handover. There is no pre-written brief — read the "
            f"predecessor bundle at {self.home.history_dir}/{source_id}/{chat_id}/ (transcript.jsonl + "
            f"subagents/ + tool-results/), write yourself a short brief of the task and its state, then begin."
        )

    def only_op_id(self) -> str:
        ops = sorted(path.name for path in self.home.chat_ops_dir.iterdir())
        self.assertEqual(len(ops), 1, ops)
        return ops[0]

    def exclude_lines(self) -> list[str]:
        exclude = self.git.path / ".git" / "info" / "exclude"
        return exclude.read_text().splitlines() if exclude.is_file() else []

