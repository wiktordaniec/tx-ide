    def standalone_layout(
        self, label: str, *, link_target: str = "current/bin/codex", executable_symlink: bool = True,
        current_is_dir: bool = False, current_target: str = "releases/1.0",
    ) -> tuple[Path, Path]:
        """Build `<root>/<label>/cx` (CODEX_HOME) + `<root>/<label>/bin` (PATH head) per the spec's
        layout; returns (codex_home, bin_dir). The fake codex is copied to `releases/1.0/bin/codex`
        and `releases/1.0/codex`."""
        base = self.root / label
        codex_home = base / "cx"
        release = codex_home / "packages" / "standalone" / "releases" / "1.0"
        (release / "bin").mkdir(parents=True)
        fake = self.fakes.bin_dir / "codex"
        shutil.copy2(fake, release / "bin" / "codex")
        shutil.copy2(fake, release / "codex")
        current = codex_home / "packages" / "standalone" / "current"
        if current_is_dir:
            shutil.copytree(release, current)
        else:
            current.symlink_to(current_target)
        bin_dir = base / "bin"
        bin_dir.mkdir()
        if executable_symlink:
            (bin_dir / "codex").symlink_to(codex_home / "packages" / "standalone" / link_target)
        else:
            shutil.copy2(fake, bin_dir / "codex")
        curl = bin_dir / "curl"
        curl.write_text(CURL_STUB)
        curl.chmod(0o755)
        (self.root / "elsewhere").mkdir(exist_ok=True)
        shutil.copy2(fake, self.root / "elsewhere" / "codex")
        return codex_home, bin_dir

    def standalone_env(self, bin_dir: Path, **extra: str) -> dict[str, str]:
        base = self.tx_env()
        env = {"PATH": f"{bin_dir}{os.pathsep}{base['PATH']}", "CURL_STUB_OUT": str(self.root / "curl-out")}
        env.update(extra)
        return env

    def curl_dumps(self) -> list[dict]:
        directory = self.root / "curl-out"
        if not directory.is_dir():
            return []
        return [json.loads(path.read_text()) for path in sorted(directory.iterdir())]

    def update_log(self) -> Path:
        return self.home.path / "codex-update" / "update.log"

