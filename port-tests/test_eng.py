    def test_t_eng_01_effort_levels_and_default(self):
        _, dump = self.spawn("c0", "--engine", "claude")
        self.assertEqual(dump["argv"][dump["argv"].index("--effort") + 1], "high")
        tiers = {1: "low", 2: "medium", 3: "high", 4: "xhigh", 5: "max"}
        for effort, tier in tiers.items():
            _, dump = self.spawn(f"c{effort}", "--engine", "claude", "--effort", str(effort))
            self.assertEqual(dump["argv"][dump["argv"].index("--effort") + 1], tier)
            _, dump = self.spawn(f"x{effort}", "--engine", "codex", "--effort", str(effort))
            self.assertIn(f"model_reasoning_effort={tier}", dump["argv"])
            self.assertEqual(dump["argv"][dump["argv"].index("-c") + 1], f"model_reasoning_effort={tier}")
        for bad in ("0", "6"):
            result = self.tx(["spawn", "bad", "--tag", "t", "--engine", "claude", "--effort", bad, "--cwd", self.repo])
            self.assertEqual(result.code, 2)
            self.assertTrue(
                result.err.rstrip().endswith(
                    f"tx spawn: error: argument --effort: invalid choice: '{bad}' (choose from '1', '2', '3', '4', '5')"
                ),
                result.err,
            )
            self.assertEqual(self.tx(["show", "bad"]).code, 1)

