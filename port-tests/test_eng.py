    def test_t_eng_19_claude_resume_fork_seed_command_exact_argv(self):
        src = 'claude --model opus --effort high --no-chrome --append-system-prompt P --dangerously-skip-permissions "seed"'
        persona = ["--model", "opus", "--effort", "high", "--no-chrome", "--append-system-prompt", "P"]

        _, chat_id = self.source("s0", "")
        self.tx(["resume", "s0"])
        record = self.show("s0")
        self.assertEqual(argv_of(self.fakes.wait_dump("claude", record["id"])), ["claude", "--resume", chat_id, CLAUDE_YOLO])

        source_id, chat_id = self.source("s", src, chat="c1", transcript='{"type":"user"}\n')
        result = self.tx(["resume", "s", "--as", "s-resumed"])
        self.assertEqual(result.code, 0, result.err)
        record = self.show("s-resumed")
        self.assertEqual(
            argv_of(self.fakes.wait_dump("claude", record["id"])),
            ["claude", "--resume", "c1", *persona, CLAUDE_YOLO],
        )
        _, dump = self.fork("s", "s-fork")
        self.assertEqual(argv_of(dump), ["claude", "--resume", "c1", "--fork-session", *persona, CLAUDE_YOLO])

        result = self.tx(["handover", "s", "t", "s-ho", "--self-catch-up"])
        self.assertEqual(result.code, 0, result.err)
        seed = self.self_catch_up_seed(source_id, "c1")
